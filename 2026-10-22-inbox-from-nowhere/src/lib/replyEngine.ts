import { comebackRules, emptyReplyComeback, exactComebacks, fallbackComebacks } from '../data/comebacks';
import { makePreview } from '../data/emails';
import type { Email } from '../types';
import { hashString, makeId } from './random';

export interface Comeback {
  text: string;
  /** Which rule matched, or "fallback" / "empty". */
  ruleId: string;
}

function escapeRegExp(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function matches(text: string, keyword: string): boolean {
  if (!/^[a-z]/i.test(keyword)) return text.includes(keyword);
  // Whole word, allowing simple suffixes: finish -> finished, repo -> repos.
  const re = new RegExp(`\\b${escapeRegExp(keyword)}(s|es|ed|ing|d)?\\b`, 'i');
  return re.test(text);
}

/**
 * Deterministic keyword-based comeback. Same input, same output.
 * It does not understand the reply; it recognizes a few words.
 */
export function getComeback(reply: string): Comeback {
  const text = reply.trim().toLowerCase();
  if (!text) return { text: emptyReplyComeback, ruleId: 'empty' };

  const normalized = text.replace(/[^a-z0-9\s]/g, '').replace(/\s+/g, ' ').trim();
  if (Object.prototype.hasOwnProperty.call(exactComebacks, normalized)) return { text: exactComebacks[normalized], ruleId: 'exact' };

  const h = hashString(text);
  for (const rule of comebackRules) {
    if (rule.keywords.some((k) => matches(text, k))) {
      return { text: rule.responses[h % rule.responses.length], ruleId: rule.id };
    }
  }
  return { text: fallbackComebacks[h % fallbackComebacks.length], ruleId: 'fallback' };
}

/** Wrap a comeback as an email from the original sender. */
export function buildComebackEmail(original: Email, reply: string, now = Date.now()): Email {
  const { text } = getComeback(reply);
  const quoted = reply
    .trim()
    .split('\n')
    .map((line) => `> ${line}`)
    .join('\n');
  const body = `${text}\n\n${quoted || '> (nothing)'}\n\nThis reply was generated by an automated comeback system that matches keywords. It did not understand you. Nobody here does.`;
  const subject = original.subject.startsWith('Re: ') ? original.subject : `Re: ${original.subject}`;
  return {
    id: makeId('reply'),
    sender: { ...original.sender },
    subject,
    preview: makePreview(text),
    body,
    timestamp: new Date(now).toISOString(),
    intensity: original.intensity,
    category: original.category,
    read: false,
    starred: false,
    folder: 'inbox',
    generated: true,
  };
}
