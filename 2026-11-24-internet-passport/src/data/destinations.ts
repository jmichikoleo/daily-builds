// src/data/destinations.ts
// the curated directory. every url here was opened and checked on 2026-11-24.
// to add a destination, copy an entry, give it a new stable id (never rename ids,
// saved passports point at them) and pick a shape + glyph pair nobody else uses.
// `npm test` checks ids, territories, glyphs and that every stamp design is unique.

import type { Destination, StampDesign, TerritoryId, StampShape, StampBorder, Rarity } from "../types";

// a second ink per territory so stamps in one territory do not all look alike
const INKS: Record<TerritoryId, string[]> = {
  creative: ["#A2465A", "#7A3550", "#B85C4A"],
  science: ["#4F6B4A", "#3E5D6B", "#6B7A3A"],
  sound: ["#2F4F6E", "#3D3F7A", "#2E6670"],
  frontier: ["#2C5C5C", "#355B3F", "#3A4A6A"],
  oddlands: ["#93630F", "#A0461E", "#6E6A12"],
  archive: ["#6B4527", "#5A3A3A", "#7A5A1E"],
  playground: ["#A2412A", "#8A2E4A", "#B0601A"],
  quiet: ["#4B5277", "#5E5A7E", "#3F6A7A"],
  hidden: ["#4A2A4F", "#2B2B4F", "#5B2C3A"],
};

let counter = 0;
function stamp(t: TerritoryId, shape: StampShape, glyph: string, border: StampBorder, label: string): StampDesign {
  counter += 1;
  const inks = INKS[t];
  // deterministic tilt between -9 and 9 degrees
  const tilt = ((counter * 37) % 19) - 9;
  return { shape, glyph, border, label, ink: inks[counter % inks.length], tilt };
}

type Row = Omit<Destination, "stamp" | "territory" | "rarity"> & {
  rarity?: Rarity;
  s: [StampShape, string, StampBorder, string];
};

function territoryRows(t: TerritoryId, rows: Row[]): Destination[] {
  return rows.map(({ s, rarity, ...rest }) => ({
    ...rest,
    territory: t,
    rarity: rarity ?? (t === "hidden" ? "secret" : "common"),
    stamp: stamp(t, s[0], s[1], s[2], s[3]),
  }));
}

