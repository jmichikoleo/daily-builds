export const DESTINATIONS: Destination[] = [
  ...creative,
  ...science,
  ...sound,
  ...frontier,
  ...oddlands,
  ...archive,
  ...playground,
  ...quiet,
  ...hidden,
];

export const REGULAR_DESTINATIONS = DESTINATIONS.filter((d) => d.territory !== "hidden");
export const SECRET_DESTINATIONS = DESTINATIONS.filter((d) => d.territory === "hidden");

const byId = new Map(DESTINATIONS.map((d) => [d.id, d]));

export function destination(id: string): Destination | undefined {
  return byId.get(id);
}

export function destinationsIn(t: TerritoryId): Destination[] {
  return DESTINATIONS.filter((d) => d.territory === t);
}
